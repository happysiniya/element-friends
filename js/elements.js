const _set = (arr) => new Set(arr);
const FAMILY_SETS = {
  alkali: _set([3, 11, 19, 37, 55, 87]),
  alkaline: _set([4, 12, 20, 38, 56, 88]),
  metalloid: _set([5, 14, 32, 33, 51, 52]),
  nonmetal: _set([1, 6, 7, 8, 15, 16, 34]),
  halogen: _set([9, 17, 35, 53, 85, 117]),
  noble: _set([2, 10, 18, 36, 54, 86, 118]),
  post: _set([13, 31, 49, 50, 81, 82, 83, 84, 113, 114, 115, 116]),
};
const GASES = _set([1, 2, 7, 8, 9, 10, 17, 18, 36, 54, 86]);
const LIQUIDS = _set([35, 80]);

function familyOf(n) {
  if (n >= 57 && n <= 71) return "lanthanide";
  if (n >= 89 && n <= 103) return "actinide";
  for (const [key, set] of Object.entries(FAMILY_SETS)) if (set.has(n)) return key;
  return "transition";
}

// 주기율표 격자 위치 [행, 열]. 란타넘족은 9행, 악티늄족은 10행.
function gridPos(n) {
  if (n === 1) return [1, 1];
  if (n === 2) return [1, 18];
  if (n <= 10) return [2, n <= 4 ? n - 2 : n + 8];
  if (n <= 18) return [3, n <= 12 ? n - 10 : n];
  if (n <= 36) return [4, n - 18];
  if (n <= 54) return [5, n - 36];
  if (n >= 57 && n <= 71) return [9, n - 54];
  if (n >= 89 && n <= 103) return [10, n - 86];
  if (n <= 86) return [6, n <= 56 ? n - 54 : n - 68];
  return [7, n <= 88 ? n - 86 : n - 100];
}

function periodOf(n) {
  if (n <= 2) return 1;
  if (n <= 10) return 2;
  if (n <= 18) return 3;
  if (n <= 36) return 4;
  if (n <= 54) return 5;
  if (n <= 86) return 6;
  return 7;
}

const ELEMENTS = ELEMENT_DATA.map(([n, sym, name, en, mass, emoji, desc, where]) => {
  const [row, col] = gridPos(n);
  const family = familyOf(n);
  return {
    n, sym, name, en, mass, emoji, desc, where, row, col, family,
    period: periodOf(n),
    group: row <= 7 ? col : null,
    phase: n >= 100 ? "unknown" : GASES.has(n) ? "gas" : LIQUIDS.has(n) ? "liquid" : "solid",
    radioactive: n === 43 || n === 61 || n >= 84,
    synthetic: n === 43 || n === 61 || n >= 93,
  };
});
